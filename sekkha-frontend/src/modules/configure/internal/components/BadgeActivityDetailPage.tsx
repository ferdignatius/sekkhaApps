import { useEffect, useState } from "react"
import { useNavigate, useParams } from "@tanstack/react-router"
import {
  AwardIcon,
  LockIcon,
  AlertTriangleIcon,
  Trash2Icon,
  CheckCircle2Icon,
} from "lucide-react"
import { PageBreadcrumb } from "@/components/common/PageBreadcrumb"
import { useAuth } from "@/modules/auth"
import { badgeActivitiesApi } from "../api/configureApi"
import type { BadgeActivityDto } from "../api/configureApi"
import { Button } from "@/components/base/Button"
import { Card } from "@/components/base/Card"
import { Input } from "@/components/base/Input"
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
  DialogFooter,
} from "@/components/base/Dialog"

function toKebabCase(str: string): string {
  return str
    .toLowerCase()
    .trim()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}

export function BadgeActivityDetailPage() {
  const { badgeActivityId } = useParams({ strict: false }) as {
    badgeActivityId?: string
  }
  const navigate = useNavigate()
  const { authState } = useAuth()
  const isAdmin =
    authState.status === "authenticated" && authState.role === "admin"

  const [item, setItem] = useState<BadgeActivityDto | null>(null)
  const [loading, setLoading] = useState(true)

  // Form states
  const [label, setLabel] = useState("")
  const [bonusPoints, setBonusPoints] = useState(30)
  const [isActive, setIsActive] = useState(true)
  const [description, setDescription] = useState("")

  const [saving, setSaving] = useState(false)
  const [successNotice, setSuccessNotice] = useState(false)
  const [errorMessage, setErrorMessage] = useState<string | null>(null)

  const autoGeneratedCode = toKebabCase(label) || item?.code || ""

  // Delete & Conflict states
  const [showDeleteModal, setShowDeleteModal] = useState(false)
  const [deleting, setDeleting] = useState(false)
  const [conflictMessage, setConflictMessage] = useState<string | null>(null)

  useEffect(() => {
    let cancelled = false
    async function loadItem() {
      if (!badgeActivityId) return
      try {
        setLoading(true)
        const found = await badgeActivitiesApi.get(badgeActivityId)
        if (cancelled) return
        if (found) {
          setItem(found)
          setLabel(found.label)
          setBonusPoints(found.bonus_points)
          setIsActive(found.is_active)
          setDescription(found.description || "")
        } else {
          setErrorMessage("Badge activity not found.")
        }
      } catch (err: any) {
        if (!cancelled)
          setErrorMessage(
            err?.message || "Failed to load badge activity details."
          )
      } finally {
        if (!cancelled) setLoading(false)
      }
    }
    void loadItem()
    return () => {
      cancelled = true
    }
  }, [badgeActivityId])

  const handleUpdate = async (e: React.FormEvent) => {
    e.preventDefault()
    if (!item) return
    setErrorMessage(null)
    setSuccessNotice(false)

    if (!label.trim()) {
      setErrorMessage("Role label is required.")
      return
    }

    if (bonusPoints < 0 || bonusPoints > 100) {
      setErrorMessage("Bonus points must be between 0 and 100.")
      return
    }

    setSaving(true)
    try {
      const updated = await badgeActivitiesApi.update(item.id, {
        code: autoGeneratedCode,
        label: label.trim(),
        description: description.trim() || null,
        bonus_points: Number(bonusPoints) || 0,
        is_active: isActive,
      })
      setItem(updated)
      setSuccessNotice(true)
    } catch (err: any) {
      setErrorMessage(err?.message || "Failed to update badge activity.")
    } finally {
      setSaving(false)
    }
  }

  const handleDelete = async () => {
    if (!item) return
    setDeleting(true)
    try {
      await badgeActivitiesApi.remove(item.id)
      setShowDeleteModal(false)
      await navigate({ to: "/configure/master/badge-activity" })
    } catch (err: any) {
      setShowDeleteModal(false)
      if (err?.status === 409 || err?.code === "BADGE_ACTIVITY_IN_USE") {
        setConflictMessage(
          err?.message ||
            "Badge activity cannot be deleted because it is already linked to attendance records. Deactivate it instead."
        )
      } else {
        setErrorMessage(err?.message || "Failed to delete badge activity.")
      }
    } finally {
      setDeleting(false)
    }
  }

  const handleDeactivateInstead = async () => {
    if (!item) return
    try {
      setSaving(true)
      const updated = await badgeActivitiesApi.update(item.id, {
        is_active: false,
      })
      setItem(updated)
      setIsActive(false)
      setConflictMessage(null)
      setSuccessNotice(true)
    } catch (err: any) {
      setErrorMessage(err?.message || "Failed to deactivate badge activity.")
    } finally {
      setSaving(false)
    }
  }

  if (loading) {
    return (
      <main className="min-h-screen bg-[#fffaf0] p-6 font-sans">
        <div className="mx-auto max-w-7xl space-y-4">
          <div className="h-4 w-32 animate-pulse rounded bg-[#e5e5e5]" />
          <div className="h-48 animate-pulse rounded-[16px] bg-[#faf5e8]" />
        </div>
      </main>
    )
  }

  if (!item && errorMessage) {
    return (
      <main className="min-h-screen bg-[#fffaf0] p-6 text-center font-sans">
        <div className="mx-auto max-w-md rounded-[16px] border border-[#e5e5e5] bg-[#faf5e8] p-8 shadow-2xs">
          <AlertTriangleIcon className="mx-auto size-12 text-destructive" />
          <h2 className="mt-4 text-base font-bold text-[#0a0a0a]">
            Badge Activity Not Found
          </h2>
          <p className="mt-1 text-xs text-[#6a6a6a]">{errorMessage}</p>
          <Button
            onClick={() =>
              void navigate({ to: "/configure/master/badge-activity" })
            }
            className="mt-6 rounded-[12px] bg-[#0a0a0a] text-xs font-bold text-white hover:bg-[#262626]"
          >
            Back to List
          </Button>
        </div>
      </main>
    )
  }

  return (
    <main className="min-h-screen bg-[#fffaf0] p-4 font-sans text-[#0a0a0a] sm:p-6 lg:p-8">
      <div className="mx-auto max-w-7xl space-y-6">
        {/* Breadcrumb Navigation */}
        <PageBreadcrumb
          items={[
            { label: "Configure", href: "/configure/master/badge-activity" },
            {
              label: "Badge Activity",
              href: "/configure/master/badge-activity",
            },
            { label: item?.label || "Details" },
          ]}
          onBack={() =>
            void navigate({ to: "/configure/master/badge-activity" })
          }
        />

        {/* Header Section */}
        <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
          <div>
            <div className="flex items-center gap-2">
              <span className="flex size-9 items-center justify-center rounded-[10px] bg-clay-ochre/20 text-[#0a0a0a]">
                <AwardIcon className="size-5 text-clay-ochre" />
              </span>
              <h1 className="text-xl font-black text-[#0a0a0a] sm:text-2xl">
                {item?.label}
              </h1>
            </div>
            <p className="mt-1 font-mono text-xs text-[#6a6a6a]">
              System Code: {item?.code}
            </p>
          </div>

          {isAdmin && (
            <Button
              type="button"
              variant="outline"
              onClick={() => setShowDeleteModal(true)}
              className="self-start rounded-[10px] border border-destructive/30 text-xs font-bold text-destructive hover:bg-destructive/10 sm:self-auto"
            >
              <Trash2Icon className="mr-1.5 size-3.5" />
              <span>Delete Role</span>
            </Button>
          )}
        </div>

        {/* Success Alert */}
        {successNotice && (
          <div className="flex items-center justify-between rounded-[12px] border border-clay-success/30 bg-clay-success/15 p-3 text-xs text-clay-success">
            <div className="flex items-center gap-2">
              <CheckCircle2Icon className="size-4 text-clay-success" />
              <span>Badge activity updated successfully.</span>
            </div>
            <button
              onClick={() => setSuccessNotice(false)}
              className="font-bold underline"
            >
              Dismiss
            </button>
          </div>
        )}

        {/* Error Alert */}
        {errorMessage && (
          <div className="flex items-center gap-2 rounded-[12px] border border-destructive/30 bg-destructive/10 p-3 text-xs text-destructive">
            <AlertTriangleIcon className="size-4 text-destructive" />
            <span>{errorMessage}</span>
          </div>
        )}

        {/* Main Edit Form */}
        <Card className="rounded-[16px] border border-[#e5e5e5] bg-[#faf5e8] p-6 shadow-2xs">
          <form onSubmit={(e) => void handleUpdate(e)} className="space-y-5">
            {/* Role Name */}
            <div>
              <label
                htmlFor="label"
                className="block text-xs font-bold tracking-wider text-[#0a0a0a] uppercase"
              >
                Role Name / Label <span className="text-destructive">*</span>
              </label>
              <Input
                id="label"
                type="text"
                disabled={!isAdmin || saving}
                required
                value={label}
                onChange={(e) => setLabel(e.target.value)}
                className="mt-1.5 h-10 w-full rounded-[10px] border border-[#e5e5e5] bg-[#fffaf0] px-3 text-xs font-semibold text-[#0a0a0a] placeholder:text-[#8a8a8a] focus:border-[#0a0a0a] focus:bg-[#fffaf0] focus:outline-none disabled:bg-[#ebe6d6]"
              />
            </div>

            {/* Code Field (Auto-synced Read-Only) */}
            <div>
              <div className="flex items-center justify-between">
                <label className="block text-xs font-bold tracking-wider text-[#0a0a0a] uppercase">
                  System Code
                </label>
                <span className="flex items-center gap-1 text-[11px] font-medium text-[#6a6a6a]">
                  <LockIcon className="size-3" /> Read-Only (Auto-synced)
                </span>
              </div>
              <div className="mt-1.5 flex h-10 w-full items-center rounded-[10px] border border-[#e5e5e5] bg-[#ebe6d6] px-3 font-mono text-xs font-bold text-[#3a3a3a]">
                {autoGeneratedCode}
              </div>
              <p className="mt-1 text-[11px] text-[#6a6a6a]">
                System code automatically synchronizes with the role label in
                kebab-case format.
              </p>
            </div>

            {/* Bonus Points */}
            <div>
              <label
                htmlFor="bonusPoints"
                className="block text-xs font-bold tracking-wider text-[#0a0a0a] uppercase"
              >
                Bonus Points Reward <span className="text-destructive">*</span>
              </label>
              <div className="relative mt-1.5">
                <Input
                  id="bonusPoints"
                  type="number"
                  min={0}
                  max={100}
                  disabled={!isAdmin || saving}
                  required
                  value={bonusPoints}
                  onChange={(e) => setBonusPoints(Number(e.target.value))}
                  className="h-10 w-full rounded-[10px] border border-[#e5e5e5] bg-[#fffaf0] pr-12 pl-3 text-xs font-bold text-[#0a0a0a] placeholder:text-[#8a8a8a] focus:border-[#0a0a0a] focus:bg-[#fffaf0] focus:outline-none disabled:bg-[#ebe6d6]"
                />
                <span className="absolute top-1/2 right-3 -translate-y-1/2 text-xs font-bold text-[#6a6a6a]">
                  Pts
                </span>
              </div>
            </div>

            {/* Description */}
            <div>
              <label
                htmlFor="description"
                className="block text-xs font-bold tracking-wider text-[#0a0a0a] uppercase"
              >
                Description / Responsibilities
              </label>
              <textarea
                id="description"
                rows={3}
                disabled={!isAdmin || saving}
                value={description}
                onChange={(e) => setDescription(e.target.value)}
                placeholder="Describe role responsibilities and scope..."
                className="mt-1.5 w-full rounded-[10px] border border-[#e5e5e5] bg-[#fffaf0] p-3 text-xs text-[#0a0a0a] placeholder:text-[#8a8a8a] focus:border-[#0a0a0a] focus:bg-[#fffaf0] focus:outline-none disabled:bg-[#ebe6d6]"
              />
            </div>

            {/* Active Status Switch */}
            <div className="flex items-center justify-between rounded-[12px] border border-[#e5e5e5] bg-[#fffaf0] p-3.5">
              <div>
                <p className="text-xs font-bold text-[#0a0a0a]">
                  Active Status
                </p>
                <p className="text-[11px] text-[#6a6a6a]">
                  When active, this role appears in event attendance dropdowns.
                </p>
              </div>
              <input
                type="checkbox"
                disabled={!isAdmin || saving}
                checked={isActive}
                onChange={(e) => setIsActive(e.target.checked)}
                className="size-4 accent-[#0a0a0a] disabled:opacity-50"
              />
            </div>

            {/* Action Buttons */}
            {isAdmin && (
              <div className="flex justify-end gap-2.5 pt-4">
                <Button
                  type="button"
                  variant="outline"
                  disabled={saving}
                  onClick={() =>
                    void navigate({ to: "/configure/master/badge-activity" })
                  }
                  className="rounded-[10px] border border-[#e5e5e5] bg-[#fffaf0] text-xs font-bold text-[#0a0a0a] hover:bg-[#ebe6d6]"
                >
                  Cancel
                </Button>
                <Button
                  type="submit"
                  disabled={saving}
                  className="rounded-[10px] bg-[#0a0a0a] px-5 text-xs font-bold text-white hover:bg-[#262626]"
                >
                  {saving ? "Saving Changes..." : "Save Changes"}
                </Button>
              </div>
            )}
          </form>
        </Card>
      </div>

      {/* Delete Confirmation Modal */}
      <Dialog
        open={showDeleteModal}
        onOpenChange={(open) => !open && setShowDeleteModal(false)}
      >
        <DialogContent className="max-w-md rounded-[20px] border border-[#e5e5e5] bg-[#fffaf0] p-6 shadow-md">
          <DialogHeader>
            <DialogTitle className="flex items-center gap-2 text-base font-black text-[#0a0a0a]">
              <AlertTriangleIcon className="size-5 text-destructive" />
              <span>Delete Badge Activity</span>
            </DialogTitle>
            <DialogDescription className="mt-2 text-xs text-[#6a6a6a]">
              Are you sure you want to permanently delete{" "}
              <strong className="text-[#0a0a0a]">{item?.label}</strong> (
              <code>{item?.code}</code>)? This action cannot be undone.
            </DialogDescription>
          </DialogHeader>

          <DialogFooter className="mt-6 flex justify-end gap-2">
            <Button
              variant="outline"
              disabled={deleting}
              onClick={() => setShowDeleteModal(false)}
              className="rounded-[10px] border border-[#e5e5e5] bg-[#faf5e8] text-xs font-bold text-[#0a0a0a] hover:bg-[#ebe6d6]"
            >
              Cancel
            </Button>
            <Button
              disabled={deleting}
              onClick={() => void handleDelete()}
              className="rounded-[10px] bg-destructive text-xs font-bold text-white hover:bg-destructive/90"
            >
              {deleting ? "Deleting..." : "Delete Permanently"}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>

      {/* 409 In-Use Conflict Mitigation Modal */}
      <Dialog
        open={Boolean(conflictMessage)}
        onOpenChange={(open) => !open && setConflictMessage(null)}
      >
        <DialogContent className="max-w-md rounded-[20px] border border-[#e5e5e5] bg-[#fffaf0] p-6 shadow-md">
          <DialogHeader>
            <DialogTitle className="flex items-center gap-2 text-base font-black text-clay-ochre">
              <AlertTriangleIcon className="size-5 text-clay-ochre" />
              <span>Cannot Delete In-Use Badge Activity</span>
            </DialogTitle>
            <DialogDescription className="mt-2 text-xs leading-relaxed text-[#6a6a6a]">
              {conflictMessage}
            </DialogDescription>
          </DialogHeader>

          <div className="mt-4 rounded-[12px] border border-clay-warning/30 bg-clay-warning/10 p-3.5 text-xs text-[#0a0a0a]">
            <p className="font-bold text-clay-warning">Recommended Pastoral Care Action:</p>
            <p className="mt-0.5 text-[#3a3a3a]">
              Instead of deleting, deactivate this role so it will no longer
              appear in future event attendance dropdowns while keeping past
              audit records safe.
            </p>
          </div>

          <DialogFooter className="mt-6 flex justify-end gap-2">
            <Button
              variant="outline"
              onClick={() => setConflictMessage(null)}
              className="rounded-[10px] border border-[#e5e5e5] bg-[#faf5e8] text-xs font-bold text-[#0a0a0a] hover:bg-[#ebe6d6]"
            >
              Close
            </Button>
            <Button
              disabled={saving}
              onClick={() => void handleDeactivateInstead()}
              className="rounded-[10px] bg-[#0a0a0a] text-xs font-bold text-white hover:bg-[#262626]"
            >
              {saving ? "Deactivating..." : "Deactivate Instead"}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </main>
  )
}
