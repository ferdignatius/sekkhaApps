import { useState } from "react"
import { useNavigate } from "@tanstack/react-router"
import {
  AwardIcon,
  CoinsIcon,
  AlertTriangleIcon,
  LockIcon,
} from "lucide-react"
import { PageBreadcrumb } from "@/components/common/PageBreadcrumb"
import { useAuth } from "@/modules/auth"
import { badgeActivitiesApi } from "../api/configureApi"
import { Button } from "@/components/base/Button"
import { Card } from "@/components/base/Card"
import { Input } from "@/components/base/Input"

function toKebabCase(str: string): string {
  return str
    .toLowerCase()
    .trim()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}

export function BadgeActivityCreatePage() {
  const navigate = useNavigate()
  const { authState } = useAuth()
  const isAdmin =
    authState.status === "authenticated" && authState.role === "admin"

  const [label, setLabel] = useState("")
  const [bonusPoints, setBonusPoints] = useState(30)
  const [isActive, setIsActive] = useState(true)
  const [description, setDescription] = useState("")

  const autoGeneratedCode = toKebabCase(label)

  const [saving, setSaving] = useState(false)
  const [errorMessage, setErrorMessage] = useState<string | null>(null)

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault()
    setErrorMessage(null)

    if (!label.trim()) {
      setErrorMessage("Role label is required.")
      return
    }

    if (bonusPoints < 0 || bonusPoints > 100) {
      setErrorMessage("Bonus points must be between 0 and 100.")
      return
    }

    setSaving(true)
    try {
      await badgeActivitiesApi.create({
        label: label.trim(),
        description: description.trim() || null,
        bonus_points: Number(bonusPoints) || 0,
        is_active: isActive,
      })
      await navigate({ to: "/configure/master/badge-activity" })
    } catch (err: any) {
      setErrorMessage(err?.message || "Failed to create badge activity.")
    } finally {
      setSaving(false)
    }
  }

  if (!isAdmin) {
    return (
      <main className="min-h-screen bg-[#fffaf0] p-6 text-center font-sans">
        <div className="mx-auto max-w-md rounded-[16px] border border-[#e5e5e5] bg-white p-8">
          <AlertTriangleIcon className="mx-auto size-12 text-[#ef4444]" />
          <h2 className="mt-4 text-base font-bold text-[#0a0a0a]">
            Access Restricted
          </h2>
          <p className="mt-1 text-xs text-[#6a6a6a]">
            Only administrators have permission to add badge activities.
          </p>
          <Button
            onClick={() =>
              void navigate({ to: "/configure/master/badge-activity" })
            }
            className="mt-6 rounded-[12px] bg-[#0a0a0a] text-xs font-bold text-white"
          >
            Back to List
          </Button>
        </div>
      </main>
    )
  }

  return (
    <main className="min-h-screen bg-[#fffaf0] p-4 font-sans text-[#0a0a0a] sm:p-6 lg:p-8">
      <div className="mx-auto max-w-7xl space-y-6">
        {/* Breadcrumb Navigation */}
        <PageBreadcrumb
          items={[
            { label: "Configure", href: "/configure/master/badge-activity" },
            {
              label: "Badge Activity",
              href: "/configure/master/badge-activity",
            },
            { label: "New Role" },
          ]}
          onBack={() =>
            void navigate({ to: "/configure/master/badge-activity" })
          }
        />

        {/* Header Section */}
        <div>
          <div className="flex items-center gap-2">
            <span className="flex size-9 items-center justify-center rounded-[10px] bg-[#fbbf24]/20 text-[#d97706]">
              <AwardIcon className="size-5" />
            </span>
            <h1 className="text-xl font-black text-[#0a0a0a] sm:text-2xl">
              Create Badge Activity
            </h1>
          </div>
          <p className="mt-1 text-xs text-[#6a6a6a]">
            Add a new service duty role for youth operational activities (MC,
            Puja Leader, Musician, etc.).
          </p>
        </div>

        {/* Error Notification */}
        {errorMessage && (
          <div className="flex items-center gap-2 rounded-[12px] border border-[#ef4444]/30 bg-[#fef2f2] p-3 text-xs text-[#b91c1c]">
            <AlertTriangleIcon className="size-4 text-[#ef4444]" />
            <span>{errorMessage}</span>
          </div>
        )}

        {/* Main Form */}
        <Card className="rounded-[16px] border border-[#e5e5e5] bg-white p-6 shadow-sm">
          <form onSubmit={(e) => void handleSubmit(e)} className="space-y-5">
            {/* Role Name */}
            <div>
              <label
                htmlFor="label"
                className="block text-xs font-bold tracking-wider text-[#0a0a0a] uppercase"
              >
                Role Name / Label <span className="text-[#ef4444]">*</span>
              </label>
              <Input
                id="label"
                type="text"
                required
                value={label}
                onChange={(e) => setLabel(e.target.value)}
                placeholder="e.g. Master of Ceremony (MC)"
                className="mt-1.5 h-10 w-full rounded-[10px] border border-[#e5e5e5] bg-[#fffaf0]/60 px-3 text-xs font-semibold text-[#0a0a0a] focus:border-[#0a0a0a] focus:bg-white focus:outline-none"
              />
            </div>

            {/* Auto Code (Read-Only) */}
            <div>
              <div className="flex items-center justify-between">
                <label className="block text-xs font-bold tracking-wider text-[#0a0a0a] uppercase">
                  System Code
                </label>
                <span className="flex items-center gap-1 text-[11px] font-medium text-[#6a6a6a]">
                  <LockIcon className="size-3" /> Auto-generated (Read-Only)
                </span>
              </div>
              <div className="mt-1.5 flex h-10 w-full items-center rounded-[10px] border border-[#e5e5e5] bg-[#f5f5f5] px-3 font-mono text-xs font-bold text-[#525252]">
                {autoGeneratedCode || "auto-generated-code"}
              </div>
              <p className="mt-1 text-[11px] text-[#8c8c8c]">
                Unique kebab-case identifier generated from role name.
              </p>
            </div>

            {/* Bonus Points */}
            <div>
              <label
                htmlFor="bonusPoints"
                className="block text-xs font-bold tracking-wider text-[#0a0a0a] uppercase"
              >
                Bonus Points Reward <span className="text-[#ef4444]">*</span>
              </label>
              <div className="relative mt-1.5">
                <Input
                  id="bonusPoints"
                  type="number"
                  min={0}
                  max={100}
                  required
                  value={bonusPoints}
                  onChange={(e) => setBonusPoints(Number(e.target.value))}
                  className="h-10 w-full rounded-[10px] border border-[#e5e5e5] bg-[#fffaf0]/60 pr-12 pl-3 text-xs font-bold text-[#0a0a0a] focus:border-[#0a0a0a] focus:bg-white focus:outline-none"
                />
                <span className="absolute top-1/2 right-3 -translate-y-1/2 text-xs font-bold text-[#6a6a6a]">
                  Pts
                </span>
              </div>
              <p className="mt-1 flex items-center gap-1 text-[11px] text-[#8c8c8c]">
                <CoinsIcon className="size-3 text-[#d97706]" />
                Standard appreciation: +30 Pts per duty service.
              </p>
            </div>

            {/* Description */}
            <div>
              <label
                htmlFor="description"
                className="block text-xs font-bold tracking-wider text-[#0a0a0a] uppercase"
              >
                Description / Responsibilities (Optional)
              </label>
              <textarea
                id="description"
                rows={3}
                value={description}
                onChange={(e) => setDescription(e.target.value)}
                placeholder="Describe role responsibilities and scope in temple activities..."
                className="mt-1.5 w-full rounded-[10px] border border-[#e5e5e5] bg-[#fffaf0]/60 p-3 text-xs text-[#0a0a0a] placeholder:text-[#999999] focus:border-[#0a0a0a] focus:bg-white focus:outline-none"
              />
            </div>

            {/* Active Toggle Switch */}
            <div className="flex items-center justify-between rounded-[12px] border border-[#f0f0f0] bg-[#fafafa] p-3.5">
              <div>
                <p className="text-xs font-bold text-[#0a0a0a]">
                  Active Status
                </p>
                <p className="text-[11px] text-[#6a6a6a]">
                  When active, this role appears in event attendance dropdowns.
                </p>
              </div>
              <input
                type="checkbox"
                checked={isActive}
                onChange={(e) => setIsActive(e.target.checked)}
                className="size-4 accent-[#16a34a]"
              />
            </div>

            {/* Buttons */}
            <div className="flex justify-end gap-2.5 pt-4">
              <Button
                type="button"
                variant="outline"
                disabled={saving}
                onClick={() =>
                  void navigate({ to: "/configure/master/badge-activity" })
                }
                className="rounded-[10px] border-[#e5e5e5] text-xs font-bold text-[#0a0a0a]"
              >
                Cancel
              </Button>
              <Button
                type="submit"
                disabled={saving}
                className="rounded-[10px] bg-[#0a0a0a] px-5 text-xs font-bold text-white hover:bg-[#262626]"
              >
                {saving ? "Creating..." : "Save Badge Activity"}
              </Button>
            </div>
          </form>
        </Card>
      </div>
    </main>
  )
}
