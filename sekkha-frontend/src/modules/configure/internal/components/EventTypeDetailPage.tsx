import { useEffect, useState } from "react"
import { useNavigate, useParams } from "@tanstack/react-router"
import {
  TagIcon,
  Bolt,
  LockIcon,
  AlertTriangleIcon,
  Trash2Icon,
  CheckCircle2Icon,
  FlameIcon,
  ShieldCheckIcon,
  CheckIcon,
} from "lucide-react"
import { PageBreadcrumb } from "@/components/common/PageBreadcrumb"
import { useAuth } from "@/modules/auth"
import { eventTypesApi } from "../api/configureApi"
import type { EventTypeDto, TargetAudienceRole } from "../api/configureApi"
import {
  TARGET_ROLE_OPTIONS,
  deriveVisibilityFromTargetRoles,
  normalizeTargetRoles,
  toggleTargetRoleSelection,
} from "@/lib/eventAudience"
import { Button } from "@/components/base/Button"
import { Card } from "@/components/base/Card"
import { Input } from "@/components/base/Input"
import { toast } from "@/components/base"
import { Switch } from "@/components/ui/switch"
import {
  parseBoundedInteger,
  sanitizeIntegerInput,
} from "@/lib/numericInput"
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
  DialogFooter,
} from "@/components/base/Dialog"

function toKebabCase(str: string): string {
  return str
    .toLowerCase()
    .trim()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}

export function EventTypeDetailPage() {
  const { categoryId } = useParams({ strict: false }) as { categoryId?: string }
  const navigate = useNavigate()
  const { authState } = useAuth()
  const isAdmin =
    authState.status === "authenticated" && authState.role === "admin"

  const [item, setItem] = useState<EventTypeDto | null>(null)
  const [loading, setLoading] = useState(true)

  // Form states
  const [label, setLabel] = useState("")
  const [color, setColor] = useState("#4262FF")
  const [defaultPointReward, setDefaultPointReward] = useState("50")
  const [defaultMaxLateMinutes, setDefaultMaxLateMinutes] = useState("30")
  const [defaultLatePenaltyPoints, setDefaultLatePenaltyPoints] = useState("15")
  const [defaultTargetRoles, setDefaultTargetRoles] = useState<
    TargetAudienceRole[]
  >(["member", "activist", "organizer"])
  const [countsTowardStreak, setCountsTowardStreak] = useState(true)
  const [isActive, setIsActive] = useState(true)
  const [description, setDescription] = useState("")

  const [saving, setSaving] = useState(false)
  const [successNotice, setSuccessNotice] = useState(false)
  const [errorMessage, setErrorMessage] = useState<string | null>(null)

  const autoGeneratedCode = toKebabCase(label) || item?.code || ""

  // Delete & Conflict states
  const [showDeleteModal, setShowDeleteModal] = useState(false)
  const [deleting, setDeleting] = useState(false)
  const [conflictMessage, setConflictMessage] = useState<string | null>(null)

  useEffect(() => {
    let cancelled = false
    async function loadItem() {
      if (!categoryId) return
      try {
        setLoading(true)
        const allTypes = await eventTypesApi.list()
        const found = allTypes.find((t) => t.id === categoryId)
        if (cancelled) return
        if (found) {
          setItem(found)
          setLabel(found.label)
          setColor(found.color)
          setDefaultPointReward(String(found.default_point_reward))
          const isMandatory = found.counts_toward_streak ?? true
          setCountsTowardStreak(isMandatory)
          setDefaultMaxLateMinutes(
            String(isMandatory ? (found.default_max_late_minutes ?? 30) : 0)
          )
          setDefaultLatePenaltyPoints(
            String(isMandatory ? (found.default_late_penalty_points ?? 15) : 0)
          )
          setDefaultTargetRoles(
            normalizeTargetRoles(
              found.default_target_roles,
              found.default_visibility
            )
          )
          setIsActive(found.is_active)
          setDescription(found.description || "")
        } else {
          setErrorMessage("Event type not found.")
        }
      } catch (err: any) {
        if (!cancelled)
          setErrorMessage(err?.message || "Failed to load event type details.")
      } finally {
        if (!cancelled) setLoading(false)
      }
    }
    void loadItem()
    return () => {
      cancelled = true
    }
  }, [categoryId])

  const handleUpdate = async (e: React.FormEvent) => {
    e.preventDefault()
    if (!item) return
    setErrorMessage(null)
    setSuccessNotice(false)

    if (!label.trim() || !color.trim()) {
      setErrorMessage("Label name and theme color are required.")
      return
    }

    const hexRegex = /^#[0-9A-Fa-f]{6}$/
    if (!hexRegex.test(color.trim())) {
      setErrorMessage("Color must be a valid 6-digit hex code (e.g. #4262FF).")
      return
    }

    const parsedPoints = parseBoundedInteger(defaultPointReward, 0, 10000)
    if (parsedPoints === null) {
      setErrorMessage("Default points reward must be between 0 and 10,000.")
      return
    }

    const parsedGrace = countsTowardStreak
      ? parseBoundedInteger(defaultMaxLateMinutes, 0, 180)
      : 0
    if (countsTowardStreak && parsedGrace === null) {
      setErrorMessage("Grace period must be between 0 and 180 minutes.")
      return
    }

    const parsedPenalty = countsTowardStreak
      ? parseBoundedInteger(defaultLatePenaltyPoints, 0, 100)
      : 0
    if (countsTowardStreak && parsedPenalty === null) {
      setErrorMessage("Penalty deduction must be between 0 and 100 points.")
      return
    }

    setSaving(true)
    try {
      await eventTypesApi.update(item.id, {
        code: autoGeneratedCode,
        label: label.trim(),
        color: color.trim().toUpperCase(),
        description: description.trim() || null,
        default_point_reward: parsedPoints,
        apply_late_penalty: countsTowardStreak && (parsedPenalty ?? 0) > 0,
        default_max_late_minutes: parsedGrace ?? 0,
        default_late_penalty_points: parsedPenalty ?? 0,
        default_target_roles: defaultTargetRoles,
        default_visibility: deriveVisibilityFromTargetRoles(defaultTargetRoles),
        counts_toward_streak: countsTowardStreak,
        is_active: isActive,
      })
      setSuccessNotice(true)
      setTimeout(() => setSuccessNotice(false), 3000)
      toast.success(`Category "${label.trim()}" updated successfully.`)
    } catch (err: any) {
      const msg = err?.message || "Failed to update event type."
      setErrorMessage(msg)
      toast.error(msg)
    } finally {
      setSaving(false)
    }
  }

  const handleDelete = async () => {
    if (!item) return
    setDeleting(true)
    try {
      const deletedLabel = item.label
      await eventTypesApi.remove(item.id)
      setShowDeleteModal(false)
      toast.success(`Category "${deletedLabel}" deleted.`)
      await navigate({ to: "/configure/master/event-type" })
    } catch (err: any) {
      const msg = err?.message || ""
      if (
        err?.status === 409 ||
        msg.includes("currently in use") ||
        msg.includes("relasi")
      ) {
        setConflictMessage(
          msg ||
          "This event type is already associated with existing events in the system and cannot be permanently deleted. You can deactivate it instead so it no longer appears when creating new events."
        )
        setShowDeleteModal(false)
      } else {
        const errText = msg || "Failed to delete event type."
        setErrorMessage(errText)
        toast.error(errText)
      }
    } finally {
      setDeleting(false)
    }
  }

  const handleDeactivateInstead = async () => {
    if (!item) return
    try {
      await eventTypesApi.update(item.id, { is_active: false })
      setIsActive(false)
      setConflictMessage(null)
      setSuccessNotice(true)
      toast.success(`Category "${item.label}" deactivated.`)
    } catch (err: any) {
      const msg = err?.message || "Failed to deactivate event type."
      setErrorMessage(msg)
      toast.error(msg)
    }
  }

  if (loading) {
    return (
      <main className="min-h-screen bg-[#fffaf0] p-6 text-left font-sans">
        <div className="mx-auto max-w-7xl space-y-4">
          <div className="h-8 w-40 animate-pulse rounded bg-[#e5e5e5]" />
          <div className="h-64 animate-pulse rounded-[20px] border border-[#e5e5e5] bg-[#faf5e8]" />
        </div>
      </main>
    )
  }

  if (!item) {
    return (
      <main className="min-h-screen bg-[#fffaf0] p-6 text-center font-sans">
        <div className="mx-auto max-w-md rounded-[16px] border border-[#e5e5e5] bg-[#faf5e8] p-8 shadow-2xs">
          <AlertTriangleIcon className="mx-auto size-12 text-destructive" />
          <h2 className="mt-4 text-base font-bold text-[#0a0a0a]">
            Data Not Found
          </h2>
          <p className="mt-1 text-xs text-[#6a6a6a]">
            Event type with this ID is not available in the system.
          </p>
          <Button
            onClick={() =>
              void navigate({ to: "/configure/master/event-type" })
            }
            className="mt-6 rounded-[12px] bg-[#0a0a0a] text-xs font-bold text-white hover:bg-[#262626]"
          >
            Back to List
          </Button>
        </div>
      </main>
    )
  }

  return (
    <main className="min-h-screen bg-[#fffaf0] pb-24 text-left font-sans">
      <PageBreadcrumb
        items={[
          { label: "Configure" },
          { label: "Master Data" },
          { label: "Event Types", href: "/configure/master/event-type" },
          { label: item.label },
        ]}
        onBack={() => void navigate({ to: "/configure/master/event-type" })}
      />

      <div className="mx-auto max-w-7xl space-y-6 px-3.5 py-4 sm:px-6 md:px-8">

        <Card className="rounded-[20px] border border-[#e5e5e5] bg-[#faf5e8] p-6 shadow-2xs sm:p-8">
          <div className="flex flex-col justify-between gap-4 border-b border-[#f0ece1] pb-5 sm:flex-row sm:items-center">
            <div className="flex items-center gap-3">
              <div
                className="flex size-11 items-center justify-center rounded-[14px] text-white shadow-2xs"
                style={{ backgroundColor: color }}
              >
                <TagIcon className="size-6 text-white" />
              </div>
              <div>
                <h1 className="text-xl font-bold tracking-tight text-[#0a0a0a]">
                  Edit Event Type
                </h1>
                <p className="text-xs text-[#6a6a6a]">
                  Configure visual identity, attendance point rewards, and
                  active status.
                </p>
              </div>
            </div>

            {isAdmin && (
              <Button
                type="button"
                variant="outline"
                onClick={() => setShowDeleteModal(true)}
                className="h-9 gap-1.5 rounded-[12px] border border-destructive/30 text-xs font-bold text-destructive hover:bg-destructive/10"
              >
                <Trash2Icon className="size-3.5" />
                Delete
              </Button>
            )}
          </div>

          {successNotice && (
            <div className="mt-5 flex items-center gap-2 rounded-[12px] border border-clay-success/30 bg-clay-success/15 p-3 text-xs font-bold text-clay-success">
              <CheckCircle2Icon className="size-4 shrink-0" />
              <span>Event type changes saved successfully.</span>
            </div>
          )}

          {errorMessage && (
            <div className="mt-5 flex items-center gap-2 rounded-[12px] border border-destructive/30 bg-destructive/10 p-3 text-xs text-destructive">
              <AlertTriangleIcon className="size-4 shrink-0 text-destructive" />
              <span>{errorMessage}</span>
            </div>
          )}

          <form onSubmit={handleUpdate} className="mt-6 space-y-5">
            {/* Semantic Code (Auto-synced Read-Only) */}
            <div className="space-y-1.5">
              <div className="flex items-center justify-between">
                <label className="text-xs font-semibold text-[#0a0a0a]">
                  System Code
                </label>
                <span className="inline-flex items-center gap-1 text-[11px] font-bold text-[#8a7a5a]">
                  <LockIcon className="size-3" /> Read-Only (Auto-synced)
                </span>
              </div>
              <Input
                disabled
                readOnly
                value={autoGeneratedCode}
                className="cursor-not-allowed bg-[#ebe6d6] font-mono text-xs font-bold text-[#6a6a6a] opacity-90"
                helperText="System code automatically synchronizes with the event type name in kebab-case format."
                startIcon={<LockIcon className="size-4 text-[#8a7a5a]" />}
              />
            </div>

            {/* Label Field */}
            <div className="space-y-1.5">
              <Input
                label="Event Type Name (Display Label)"
                required
                disabled={!isAdmin}
                value={label}
                onChange={(e) => setLabel(e.target.value)}
                helperText="Display name shown on the activity calendar and dropdown options."
              />
            </div>

            {/* Color Swatch & Preset */}
            <div className="space-y-2">
              <label className="text-xs font-semibold text-[#0a0a0a]">
                Theme Color
              </label>
              <div className="flex items-center gap-3">
                <input
                  type="color"
                  disabled={!isAdmin}
                  value={color}
                  onChange={(e) => setColor(e.target.value)}
                  className="size-11 cursor-pointer rounded-[12px] border border-[#e5e5e5] bg-[#fffaf0] p-1 shadow-2xs disabled:cursor-not-allowed"
                />
                <Input
                  disabled={!isAdmin}
                  className="border border-[#e5e5e5] bg-[#fffaf0] font-mono uppercase text-[#0a0a0a]"
                  value={color}
                  onChange={(e) => setColor(e.target.value)}
                  placeholder="#4262FF"
                />
              </div>
            </div>

            {/* Default Point Reward */}
            <div className="space-y-1.5">
              <Input
                label="Default Karma Points Reward"
                type="text"
                inputMode="numeric"
                pattern="[0-9]*"
                required
                disabled={!isAdmin}
                value={defaultPointReward}
                onChange={(e) =>
                  setDefaultPointReward(sanitizeIntegerInput(e.target.value))
                }
                startIcon={<Bolt className="size-4 text-clay-ochre" />}
                helperText="Default reward points for events of this type (0 - 10,000)."
              />
            </div>

            {/* Default Access Right, Mandatory Streak & Late Arrival Policy */}
            <div className="space-y-4 rounded-[14px] border border-[#e5e5e5] bg-[#fffaf0] p-4">
              <div className="space-y-2">
                <div className="flex items-center gap-1.5">
                  <ShieldCheckIcon className="size-4 text-[#0a0a0a]" />
                  <span className="text-xs font-bold text-[#0a0a0a]">
                    Default Access Right (Target Roles)
                  </span>
                </div>
                <p className="text-[11px] text-[#6a6a6a]">
                  Select one or more roles that can view events in this
                  category. Organizers and admins can always manage all events.
                </p>
                <div
                  role="group"
                  aria-label="Default Access Right"
                  className="grid grid-cols-3 gap-2"
                >
                  {TARGET_ROLE_OPTIONS.map((opt) => {
                    const selected = defaultTargetRoles.includes(opt.value)
                    return (
                      <button
                        key={opt.value}
                        type="button"
                        role="checkbox"
                        aria-checked={selected}
                        disabled={!isAdmin}
                        onClick={() =>
                          setDefaultTargetRoles((prev) =>
                            toggleTargetRoleSelection(prev, opt.value)
                          )
                        }
                        className={`flex min-h-[38px] cursor-pointer items-center justify-center gap-1.5 rounded-xl border px-3 py-1.5 text-xs font-bold transition-all disabled:cursor-not-allowed disabled:opacity-60 ${
                          selected
                            ? "border-[#0a0a0a] bg-[#0a0a0a] text-white shadow-2xs"
                            : "border-[#e5e5e5] bg-[#faf5e8] text-[#6a6a6a] hover:bg-[#ebe6d6] hover:text-[#0a0a0a]"
                        }`}
                      >
                        {selected && <CheckIcon className="size-3.5 shrink-0" />}
                        <span>{opt.label}</span>
                      </button>
                    )
                  })}
                </div>
              </div>

              <div className="space-y-3 border-t border-[#e5e5e5] pt-3.5">
                <div className="flex items-center justify-between gap-4">
                  <div className="space-y-0.5">
                    <label
                      htmlFor="et-detail-counts-streak"
                      className="flex cursor-pointer items-center gap-1.5 text-xs font-bold text-[#0a0a0a]"
                    >
                      <FlameIcon className="size-3.5 text-[#c28e20]" />
                      <span>
                        {countsTowardStreak
                          ? "Mandatory Event (Affects Weekly Streak)"
                          : "Optional Event (Does Not Affect Streak)"}
                      </span>
                    </label>
                    <p className="text-[11px] text-[#6a6a6a]">
                      {countsTowardStreak
                        ? "Tracks weekly attendance streaks and applies the late arrival policy below (set Penalty Deduction to 0 for no deduction)."
                        : "Optional events do not affect weekly streaks and never apply late penalties."}
                    </p>
                  </div>
                  <Switch
                    id="et-detail-counts-streak"
                    disabled={!isAdmin}
                    checked={countsTowardStreak}
                    onCheckedChange={(checked) => {
                      setCountsTowardStreak(checked)
                      if (checked) {
                        if (!defaultMaxLateMinutes || defaultMaxLateMinutes === "0") {
                          setDefaultMaxLateMinutes("30")
                        }
                        if (!defaultLatePenaltyPoints || defaultLatePenaltyPoints === "0") {
                          setDefaultLatePenaltyPoints("15")
                        }
                      }
                    }}
                    aria-label="Mandatory Event for Weekly Streak"
                  />
                </div>

                {countsTowardStreak && (
                  <div className="grid grid-cols-1 gap-3 rounded-xl border border-[#E5E0D5]/80 bg-[#FFF9F2] p-3.5 sm:grid-cols-2">
                    <Input
                      label="Grace Period (Minutes)"
                      type="text"
                      inputMode="numeric"
                      pattern="[0-9]*"
                      disabled={!isAdmin}
                      value={defaultMaxLateMinutes}
                      onChange={(e) =>
                        setDefaultMaxLateMinutes(sanitizeIntegerInput(e.target.value))
                      }
                      helperText="Allowed minutes after start before penalty (0 - 180)."
                    />
                    <Input
                      label="Penalty Deduction (Karma Points)"
                      type="text"
                      inputMode="numeric"
                      pattern="[0-9]*"
                      disabled={!isAdmin}
                      value={defaultLatePenaltyPoints}
                      onChange={(e) =>
                        setDefaultLatePenaltyPoints(sanitizeIntegerInput(e.target.value))
                      }
                      helperText="Points deducted when checking in late (0 - 100; 0 = no deduction)."
                    />
                  </div>
                )}
              </div>
            </div>

            {/* Description Field */}
            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-[#0a0a0a]">
                Description (Optional)
              </label>
              <textarea
                rows={3}
                maxLength={500}
                disabled={!isAdmin}
                placeholder="Brief description about this event type..."
                value={description}
                onChange={(e) => setDescription(e.target.value)}
                className="w-full rounded-[12px] border border-[#e5e5e5] bg-[#fffaf0] p-3 text-xs text-[#0a0a0a] shadow-2xs transition-colors outline-none placeholder:text-[#8a8a8a] hover:border-[#bfbfbf] focus:border-[#0a0a0a] focus:ring-2 focus:ring-[#0a0a0a]/15 disabled:cursor-not-allowed disabled:opacity-60"
              />
              <p className="text-right text-[11px] text-[#8a8a8a]">
                {description.length}/500 characters
              </p>
            </div>

            {/* Status Active Toggle */}
            <div className="flex items-center justify-between rounded-[14px] border border-[#e5e5e5] bg-[#faf5e8] p-4">
              <div>
                <p className="text-xs font-bold text-[#0a0a0a]">
                  Active Status
                </p>
                <p className="text-[11px] text-[#6a6a6a]">
                  Inactive event types are hidden from new event creation forms.
                </p>
              </div>
              <input
                type="checkbox"
                disabled={!isAdmin}
                checked={isActive}
                onChange={(e) => setIsActive(e.target.checked)}
                className="size-5 cursor-pointer accent-[#0a0a0a] disabled:cursor-not-allowed"
              />
            </div>

            {/* Action Buttons */}
            {isAdmin && (
              <div className="flex items-center justify-end gap-3 border-t border-[#f0ece1] pt-4">
                <Button
                  type="button"
                  variant="outline"
                  onClick={() =>
                    void navigate({ to: "/configure/master/event-type" })
                  }
                  className="rounded-[12px] border border-[#e5e5e5] bg-[#fffaf0] text-xs font-bold text-[#0a0a0a] hover:bg-[#ebe6d6]"
                >
                  Cancel
                </Button>
                <Button
                  type="submit"
                  disabled={saving}
                  className="gap-2 rounded-[12px] bg-[#0a0a0a] px-6 text-xs font-bold text-white shadow-xs hover:bg-[#262626]"
                >
                  {saving ? "Saving..." : "Save Changes"}
                </Button>
              </div>
            )}
          </form>
        </Card>
      </div>

      {/* Delete Confirmation Modal */}
      <Dialog open={showDeleteModal} onOpenChange={setShowDeleteModal}>
        <DialogContent className="max-w-md rounded-[20px] border border-[#e5e5e5] bg-[#fffaf0] p-6 shadow-md">
          <DialogHeader>
            <div className="mb-2 flex size-10 items-center justify-center rounded-full bg-destructive/10 text-destructive">
              <AlertTriangleIcon className="size-5" />
            </div>
            <DialogTitle className="text-base font-bold text-[#0a0a0a]">
              Delete Event Type "{item.label}"?
            </DialogTitle>
            <DialogDescription className="text-xs text-[#6a6a6a]">
              This action is permanent. If this event type is already used by at
              least one event, the database will reject deletion.
            </DialogDescription>
          </DialogHeader>
          <DialogFooter className="mt-4 flex gap-2">
            <Button
              type="button"
              variant="outline"
              onClick={() => setShowDeleteModal(false)}
              className="rounded-[12px] border border-[#e5e5e5] bg-[#faf5e8] text-xs font-bold text-[#0a0a0a] hover:bg-[#ebe6d6]"
            >
              Cancel
            </Button>
            <Button
              type="button"
              disabled={deleting}
              onClick={() => void handleDelete()}
              className="rounded-[12px] bg-destructive text-xs font-bold text-white hover:bg-destructive/90"
            >
              {deleting ? "Deleting..." : "Yes, Delete"}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>

      {/* 409 Conflict Dialog */}
      <Dialog
        open={Boolean(conflictMessage)}
        onOpenChange={(open) => !open && setConflictMessage(null)}
      >
        <DialogContent className="max-w-md rounded-[20px] border border-[#e5e5e5] bg-[#fffaf0] p-6 shadow-md">
          <DialogHeader>
            <div className="mb-2 flex size-10 items-center justify-center rounded-full bg-clay-warning/10 text-clay-warning">
              <AlertTriangleIcon className="size-5" />
            </div>
            <DialogTitle className="text-base font-bold text-[#0a0a0a]">
              Event Type Currently in Use
            </DialogTitle>
            <DialogDescription className="text-xs text-[#3a3a3a]">
              {conflictMessage}
            </DialogDescription>
          </DialogHeader>
          <div className="mt-2 rounded-[12px] border border-clay-warning/30 bg-clay-warning/10 p-3 text-xs text-[#0a0a0a]">
            💡 <strong className="text-clay-warning">Recommendation:</strong> Deactivate this event type
            instead. Past events will remain intact and this type will no longer
            appear on new event forms.
          </div>
          <DialogFooter className="mt-4 flex gap-2">
            <Button
              type="button"
              variant="outline"
              onClick={() => setConflictMessage(null)}
              className="rounded-[12px] border border-[#e5e5e5] bg-[#faf5e8] text-xs font-bold text-[#0a0a0a] hover:bg-[#ebe6d6]"
            >
              Close
            </Button>
            <Button
              type="button"
              onClick={() => void handleDeactivateInstead()}
              className="rounded-[12px] bg-[#0a0a0a] text-xs font-bold text-white hover:bg-[#262626]"
            >
              Deactivate Instead
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </main>
  )
}
