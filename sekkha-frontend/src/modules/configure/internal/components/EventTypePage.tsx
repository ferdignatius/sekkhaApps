import { useState } from "react"
import { useNavigate } from "@tanstack/react-router"
import {
  TagIcon,
  ArrowLeftIcon,
  CoinsIcon,
  AlertTriangleIcon,
  LockIcon,
} from "lucide-react"
import { PageBreadcrumb } from "@/components/common/PageBreadcrumb"
import { useAuth } from "@/modules/auth"
import { eventTypesApi } from "../api/configureApi"
import { Button } from "@/components/base/Button"
import { Card } from "@/components/base/Card"
import { Input } from "@/components/base/Input"

function toKebabCase(str: string): string {
  return str
    .toLowerCase()
    .trim()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}

export function EventTypeCreatePage() {
  const navigate = useNavigate()
  const { authState } = useAuth()
  const isAdmin =
    authState.status === "authenticated" && authState.role === "admin"

  const [label, setLabel] = useState("")
  const [color, setColor] = useState("#4262FF")
  const [defaultPointReward, setDefaultPointReward] = useState(50)
  const [isActive, setIsActive] = useState(true)
  const [description, setDescription] = useState("")

  const autoGeneratedCode = toKebabCase(label)

  const [saving, setSaving] = useState(false)
  const [errorMessage, setErrorMessage] = useState<string | null>(null)

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault()
    setErrorMessage(null)

    if (!label.trim() || !color.trim()) {
      setErrorMessage("Label name and theme color are required.")
      return
    }

    const hexRegex = /^#[0-9A-Fa-f]{6}$/
    if (!hexRegex.test(color.trim())) {
      setErrorMessage("Color must be a valid 6-digit hex code (e.g. #4262FF).")
      return
    }

    setSaving(true)
    try {
      await eventTypesApi.create({
        label: label.trim(),
        color: color.trim().toUpperCase(),
        description: description.trim() || null,
        default_point_reward: Number(defaultPointReward) || 0,
        is_active: isActive,
      })
      await navigate({ to: "/configure/master/event-type" })
    } catch (err: any) {
      setErrorMessage(err?.message || "Failed to create event type.")
    } finally {
      setSaving(false)
    }
  }

  if (!isAdmin) {
    return (
      <main className="min-h-screen bg-[#fffaf0] p-6 text-center font-sans">
        <div className="mx-auto max-w-md rounded-[16px] border border-[#e5e5e5] bg-white p-8">
          <AlertTriangleIcon className="mx-auto size-12 text-[#ef4444]" />
          <h2 className="mt-4 text-base font-bold text-[#0a0a0a]">
            Access Restricted
          </h2>
          <p className="mt-1 text-xs text-[#6a6a6a]">
            Only administrators have permission to add event types.
          </p>
          <Button
            onClick={() =>
              void navigate({ to: "/configure/master/event-type" })
            }
            className="mt-6 rounded-[12px] bg-[#0a0a0a] text-xs font-bold text-white"
          >
            Back to List
          </Button>
        </div>
      </main>
    )
  }

  return (
    <main className="min-h-screen bg-[#fffaf0] pb-24 text-left font-sans">
      <PageBreadcrumb
        items={[
          { label: "Configure" },
          { label: "Master Data" },
          { label: "Event Types" },
          { label: "Add New" },
        ]}
      />

      <div className="mx-auto max-w-3xl space-y-6 px-3.5 py-4 sm:px-6 md:px-8">
        <button
          type="button"
          onClick={() => void navigate({ to: "/configure/master/event-type" })}
          className="inline-flex items-center gap-2 text-xs font-bold text-[#6a6a6a] transition-colors hover:text-[#0a0a0a]"
        >
          <ArrowLeftIcon className="size-4" />
          Back to Event Types
        </button>

        <Card className="rounded-[20px] border border-[#e5e5e5] bg-white p-6 shadow-sm sm:p-8">
          <div className="flex items-center gap-3 border-b border-[#f0ece1] pb-5">
            <div className="flex size-11 items-center justify-center rounded-[14px] bg-[#0a0a0a] text-white">
              <TagIcon className="size-6 text-[#e8b94a]" />
            </div>
            <div>
              <h1 className="text-xl font-bold tracking-tight text-[#0a0a0a]">
                Add Event Type
              </h1>
              <p className="text-xs text-[#6a6a6a]">
                Register a new event classification in Sekkha Apps.
              </p>
            </div>
          </div>

          {errorMessage && (
            <div className="mt-5 flex items-center gap-2 rounded-[12px] border border-[#ef4444]/20 bg-[#ef4444]/10 p-3 text-xs text-[#ef4444]">
              <AlertTriangleIcon className="size-4 shrink-0" />
              <span>{errorMessage}</span>
            </div>
          )}

          <form onSubmit={handleSubmit} className="mt-6 space-y-5">
            {/* Label Field */}
            <div className="space-y-1.5">
              <Input
                label="Event Type Name (Label)"
                required
                placeholder="e.g. Regular Puja / Chanting"
                value={label}
                onChange={(e) => setLabel(e.target.value)}
                helperText="User-friendly display name for this event type."
              />
            </div>

            {/* Auto-Generated Code Field (Read Only) */}
            <div className="space-y-1.5">
              <div className="flex items-center justify-between">
                <label className="text-xs font-semibold text-[#0a0a0a]">
                  System Code
                </label>
                <span className="inline-flex items-center gap-1 text-[11px] font-bold text-[#8a7a5a]">
                  <LockIcon className="size-3" /> Read Only
                </span>
              </div>
              <Input
                disabled
                readOnly
                value={autoGeneratedCode || "auto-from-name"}
                className="cursor-not-allowed bg-[#faf5e8] font-mono text-xs font-bold text-[#6a6a6a] opacity-90"
                helperText="System code is automatically generated in kebab-case from the name and is locked (read-only)."
                startIcon={<LockIcon className="size-4 text-[#8a7a5a]" />}
              />
            </div>

            {/* Color Swatch */}
            <div className="space-y-2">
              <label className="text-xs font-semibold text-[#0a0a0a]">
                Theme Color
              </label>
              <div className="flex items-center gap-3">
                <input
                  type="color"
                  value={color}
                  onChange={(e) => setColor(e.target.value)}
                  className="size-11 cursor-pointer rounded-[12px] border border-[#e5e5e5] bg-[#fffaf0] p-1 shadow-2xs"
                />
                <Input
                  className="bg-white font-mono uppercase"
                  value={color}
                  onChange={(e) => setColor(e.target.value)}
                  placeholder="#4262FF"
                />
              </div>
            </div>

            {/* Default Point Reward */}
            <div className="space-y-1.5">
              <Input
                label="Default Points Reward"
                type="number"
                min={0}
                max={10000}
                required
                value={defaultPointReward}
                onChange={(e) =>
                  setDefaultPointReward(
                    Math.max(0, parseInt(e.target.value) || 0)
                  )
                }
                startIcon={<CoinsIcon className="size-4 text-[#e8b94a]" />}
                helperText="Default points awarded for attending events of this type (0 - 10,000)."
              />
            </div>

            {/* Description Field */}
            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-[#0a0a0a]">
                Description (Optional)
              </label>
              <textarea
                rows={3}
                maxLength={500}
                placeholder="Brief description about this event type..."
                value={description}
                onChange={(e) => setDescription(e.target.value)}
                className="w-full rounded-[12px] border border-[#e5e5e5] bg-[#fffaf0] p-3 text-xs text-[#0a0a0a] shadow-2xs transition-colors outline-none placeholder:text-[#767676] hover:border-[#bfbfbf] focus:border-[#0a0a0a] focus:ring-2 focus:ring-[#0a0a0a]/15"
              />
              <p className="text-right text-[11px] text-[#8a8a8a]">
                {description.length}/500 characters
              </p>
            </div>

            {/* Status Active Toggle */}
            <div className="flex items-center justify-between rounded-[14px] border border-[#e5e5e5] bg-[#faf5e8] p-4">
              <div>
                <p className="text-xs font-bold text-[#0a0a0a]">
                  Active Status
                </p>
                <p className="text-[11px] text-[#6a6a6a]">
                  Active event types can be selected when creating new events.
                </p>
              </div>
              <input
                type="checkbox"
                checked={isActive}
                onChange={(e) => setIsActive(e.target.checked)}
                className="size-5 cursor-pointer accent-[#0a0a0a]"
              />
            </div>

            {/* Submit Action Buttons */}
            <div className="flex items-center justify-end gap-3 border-t border-[#f0ece1] pt-4">
              <Button
                type="button"
                variant="outline"
                onClick={() =>
                  void navigate({ to: "/configure/master/event-type" })
                }
                className="rounded-[12px] text-xs font-bold"
              >
                Cancel
              </Button>
              <Button
                type="submit"
                disabled={saving}
                className="gap-2 rounded-[12px] bg-[#0a0a0a] px-6 text-xs font-bold text-white shadow-xs hover:bg-[#222]"
              >
                {saving ? "Saving..." : "Save Event Type"}
              </Button>
            </div>
          </form>
        </Card>
      </div>
    </main>
  )
}
